    def test_report_contains_ready_flag_and_structured_issue_fields(self):
        ready_dir = self.root / "ready"
        broken_dir = self.root / "broken"
        self.write_skill(ready_dir, "---\nname: ready\ndescription: Ready\n---\n\nBody.\n")
        self.write_skill(broken_dir, "---\nname: broken\ndescription: Broken\n---\n\nBody.\n")
        (ready_dir / "docs").mkdir(parents=True, exist_ok=True)
        (ready_dir / "docs" / "README.md").write_text("ready\n", encoding="utf-8")
        (broken_dir / "package.json").write_text("{not-json}\n", encoding="utf-8")
        report_path = self.root / "report.json"

        completed = subprocess.run(
            [
                sys.executable,
                str(SCRIPT_PATH),
                "--root-dir",
                str(self.root),
                "--recursive",
                "--dry-run",
                "--report",
                str(report_path),
            ],
            capture_output=True,
            text=True,
            check=False,
        )

        self.assertEqual(completed.returncode, 1, completed.stderr)
        payload = json.loads(report_path.read_text(encoding="utf-8"))
        items = {Path(item["path"]).name: item for item in payload["items"]}
        self.assertTrue(items["ready"]["readyForBatchImport"])
        self.assertEqual(items["ready"]["warningDetails"][0]["code"], "capability_already_present")
        self.assertEqual(items["broken"]["errorCode"], "invalid_package_json")
        self.assertIn("Expecting property name", items["broken"]["errorMessage"])


