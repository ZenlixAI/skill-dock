    def test_include_and_exclude_glob_filter_candidates(self):
        skill_a = self.root / "keep-skill"
        skill_b = self.root / "skip-skill"
        self.write_skill(skill_a, "---\nname: keep\ndescription: keep\n---\n\nkeep\n")
        self.write_skill(skill_b, "---\nname: skip\ndescription: skip\n---\n\nskip\n")

        completed = subprocess.run(
            [
                sys.executable,
                str(SCRIPT_PATH),
                "--root-dir",
                str(self.root),
                "--recursive",
                "--include-glob",
                "*keep*",
                "--exclude-glob",
                "*skip*",
                "--write",
                "--report",
                str(self.root / "report.json"),
            ],
            capture_output=True,
            text=True,
            check=False,
        )

        self.assertEqual(completed.returncode, 0, completed.stderr)
        self.assertTrue((skill_a / "package.json").exists())
        self.assertFalse((skill_b / "package.json").exists())

